from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Any
from datetime import datetime

from src.utils.openai_client import get_llm_client


@dataclass
class ItineraryFormatterAgent:
    """Agent that converts planning results into beautiful human-readable itinerary."""
    
    def format_itinerary(self, planning_results: Dict[str, Any], request_summary: str) -> str:
        """Convert planning results to formatted text itinerary."""
        
        llm_client = get_llm_client()
        
        # Extract key information
        agent_results = planning_results.get("final_context", {}).get("agent_results", {})
        
        prompt = f"""
Create a beautiful, professional travel itinerary in text format based on these planning results:

ORIGINAL REQUEST: {request_summary}

PLANNING RESULTS:
{self._format_results_for_llm(agent_results)}

Generate a comprehensive, well-formatted itinerary that includes:

1. Trip Overview (destination, dates, duration)
2. Flight Details (times, airlines, confirmation notes) - USE EXACT DETAILS FROM FlightAgent
3. Accommodation Details (hotel info, location, amenities) - USE EXACT DETAILS FROM HotelAgent  
4. Daily Itinerary (day-by-day schedule with times and activities) - USE ALL DAYS FROM DetailedScheduler
5. Transportation Guide (how to get around) - USE EXACT DETAILS FROM TransportAgent
6. Budget Summary (breakdown of costs)
7. Important Notes & Tips

IMPORTANT INSTRUCTIONS:
- Use the EXACT flight details, hotel names, and schedules provided by the agents
- Do NOT use placeholder text like "[Insert details]" - use the actual data provided
- Include ALL days from the daily schedule, not just the first 2 days
- Use the correct transportation information for the destination
- Calculate totals from the provided costs
- Make it destination-specific and culturally relevant

Format it as a professional travel document that someone could print and take on their trip.
Use clear headings, bullet points, and readable formatting.
Include practical details like addresses, times, and costs.

Make it comprehensive but easy to read.
"""

        try:
            formatted_itinerary = llm_client.complete(prompt)
            
            # Check if LLM used placeholders - if so, use fallback
            if "[Insert" in formatted_itinerary or "Day 3:" not in formatted_itinerary:
                return self._fallback_format(agent_results, request_summary)
            
            # Add header and footer
            header = f"""
{'='*80}
                          🌍 YOUR PERSONALIZED TRAVEL ITINERARY 🌍
{'='*80}
Generated on: {datetime.now().strftime('%B %d, %Y at %H:%M')}

"""
            
            footer = f"""

{'='*80}
                             ✈️ HAVE A WONDERFUL TRIP! ✈️
{'='*80}

Generated by Mini Task Planner - Your AI Travel Assistant
For updates or changes, please regenerate your itinerary.
"""
            
            return header + formatted_itinerary + footer
            
        except Exception as e:
            # Fallback to basic formatting
            return self._fallback_format(agent_results, request_summary)
    
    def _format_results_for_llm(self, agent_results: Dict[str, Any]) -> str:
        """Format agent results for LLM prompt."""
        formatted = ""
        
        for agent_name, results in agent_results.items():
            formatted += f"\n{agent_name} Results:\n"
            if isinstance(results, dict):
                # Format dictionary results with proper structure
                for key, value in results.items():
                    if isinstance(value, dict):
                        formatted += f"  {key}:\n"
                        for sub_key, sub_value in value.items():
                            formatted += f"    {sub_key}: {sub_value}\n"
                    elif isinstance(value, list):
                        formatted += f"  {key}: {', '.join(map(str, value))}\n"
                    else:
                        formatted += f"  {key}: {value}\n"
            else:
                formatted += f"  {results}\n"
            formatted += "\n"
        
        return formatted
    
    def _fallback_format(self, agent_results: Dict[str, Any], request_summary: str) -> str:
        """Enhanced fallback formatting that creates a complete itinerary from agent data."""
        
        # Extract data from agents
        flight_data = agent_results.get("FlightAgent", {})
        hotel_data = agent_results.get("HotelAgent", {})
        schedule_data = agent_results.get("DetailedScheduler", {})
        transport_data = agent_results.get("TransportAgent", {})
        
        # Build header
        output = f"""
{'='*80}
                          🌍 YOUR PERSONALIZED TRAVEL ITINERARY 🌍
{'='*80}
Generated on: {datetime.now().strftime('%B %d, %Y at %H:%M')}

**Trip Overview:**
- Request: {request_summary}
- Duration: 7 days

"""
        
        # Flight Details - Handle new detailed structure
        if flight_data:
            output += "**Flight Details:**\n"
            
            # Handle outbound flights
            outbound_flights = flight_data.get("outbound_options", flight_data.get("outbound_flights", []))
            if outbound_flights:
                best_outbound = outbound_flights[0]  # Take first option as selected
                output += f"- **Outbound Flight:** {best_outbound.get('airline', 'N/A')} {best_outbound.get('flight_number', 'N/A')}\n"
                output += f"  - Route: {best_outbound.get('departure_airport', 'N/A')} → {best_outbound.get('arrival_airport', 'N/A')}\n"
                output += f"  - Departure: {best_outbound.get('departure_time', 'N/A')}\n"
                output += f"  - Arrival: {best_outbound.get('arrival_time', 'N/A')}\n"
                output += f"  - Duration: {best_outbound.get('duration', 'N/A')}\n"
                output += f"  - Price: {best_outbound.get('price', 'N/A')}\n"
                if best_outbound.get('description'):
                    output += f"  - Details: {best_outbound.get('description')}\n"
                if best_outbound.get('booking_url'):
                    output += f"  - Booking: {best_outbound.get('booking_url')}\n"
            
            # Handle return flights
            return_flights = flight_data.get("return_options", flight_data.get("return_flights", []))
            if return_flights:
                best_return = return_flights[0]  # Take first option as selected
                output += f"- **Return Flight:** {best_return.get('airline', 'N/A')} {best_return.get('flight_number', 'N/A')}\n"
                output += f"  - Route: {best_return.get('departure_airport', 'N/A')} → {best_return.get('arrival_airport', 'N/A')}\n"
                output += f"  - Departure: {best_return.get('departure_time', 'N/A')}\n"
                output += f"  - Arrival: {best_return.get('arrival_time', 'N/A')}\n"
                output += f"  - Duration: {best_return.get('duration', 'N/A')}\n"
                output += f"  - Price: {best_return.get('price', 'N/A')}\n"
                if best_return.get('description'):
                    output += f"  - Details: {best_return.get('description')}\n"
                if best_return.get('booking_url'):
                    output += f"  - Booking: {best_return.get('booking_url')}\n"
            
            # Add search links if no specific flights found
            if flight_data.get("search_links"):
                output += "\n**Alternative Flight Search:**\n"
                for i, link in enumerate(flight_data["search_links"][:3], 1):  # Show top 3
                    output += f"  {i}. {link}\n"
            
            # Add recommendations
            if flight_data.get("recommendations"):
                output += "\n**Flight Recommendations:**\n"
                for rec in flight_data["recommendations"][:3]:  # Show top 3
                    output += f"  • {rec}\n"
            
            output += "\n"
        
        # Hotel Details
        if hotel_data and hotel_data.get("hotel"):
            hotel = hotel_data["hotel"]
            output += f"""**Accommodation Details:**
- Hotel: {hotel.get('name', 'N/A')}
  - Location: {hotel.get('location', 'N/A')}
  - Rating: {hotel.get('rating', 'N/A')}
  - Price per night: {hotel.get('price_per_night', 'N/A')}
  - Total Cost: {hotel.get('total_cost', 'N/A')}
  - Amenities: {', '.join(hotel.get('amenities', [])) if hotel.get('amenities') else 'N/A'}
  - Walking Distance: {hotel.get('walking_distance_to_attractions', 'N/A')}

"""
        
        # Daily Schedule
        if schedule_data and schedule_data.get("daily_schedule"):
            output += "**Daily Itinerary:**\n"
            daily_schedule = schedule_data["daily_schedule"]
            
            for day, activities in daily_schedule.items():
                output += f"- **{day}:**\n"
                if isinstance(activities, dict):
                    for time_period, activity in activities.items():
                        output += f"  - {time_period.title()}: {activity}\n"
                else:
                    output += f"  - {activities}\n"
            output += "\n"
        
        # Transportation
        if transport_data and transport_data.get("transportation"):
            transport = transport_data["transportation"]
            output += f"""**Transportation Guide:**
- Airport Transfers: {transport.get('airport_transfers', 'N/A')}
- Local Transport: {transport.get('local_transport', 'N/A')}
{f"- City Transport: {transport.get('city_transport', 'N/A')}" if transport.get('city_transport') else ""}
- Walking Distances: {transport.get('walking_distances', 'N/A')}

"""
        
        # Budget Summary
        output += f"""**Budget Summary:**
- Flights: {flight_data.get('total_cost', 'N/A')}
- Hotel: {hotel_data.get('hotel', {}).get('total_cost', 'N/A')}
- Transportation: {transport_data.get('transportation', {}).get('local_transport', 'N/A')}
- Activities: [Estimated based on planned activities]

**Important Notes & Tips:**
- Check visa requirements for your destination
- Carry appropriate identification and travel documents
- Respect local customs and traditions
- Stay hydrated and carry a map or GPS device
- Have emergency contact information readily available

{'='*80}
                             ✈️ HAVE A WONDERFUL TRIP! ✈️
{'='*80}

Generated by Mini Task Planner - Your AI Travel Assistant
For updates or changes, please regenerate your itinerary.
"""
        
        return output
